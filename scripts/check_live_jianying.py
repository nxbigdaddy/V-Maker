"""Live end-to-end check for the 剪映 (JianYing) native draft export.

Real HTTP mocks are used for the image provider so the project ends up with genuine PNG assets
(the built-in demo image provider emits SVG, which 剪映 cannot import and the exporter must skip).
The draft is then generated by the real backend, downloaded as an artifact, unpacked, and its
`draft_content.json` is verified structurally.

Requires the backend to be running with the test key:

    $env:VMAKER_TEST_IMAGE_KEY="sk-live-mock-image-key-123456"
    python -m uvicorn backend.main:app --host 127.0.0.1 --port 8765
"""
from __future__ import annotations

import base64
import io
import json
import threading
import time
import urllib.error
import urllib.request
import zipfile
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

BACKEND = "http://127.0.0.1:8765/api"
MOCK_PORT = 8802
MOCK_KEY = "sk-live-mock-image-key-123456"

from PIL import Image  # noqa: E402 - available in the bundled runtime

buffer = io.BytesIO()
Image.new("RGB", (320, 180), (38, 49, 60)).save(buffer, format="PNG")
PNG_BYTES = buffer.getvalue()
print(f"mock PNG: {len(PNG_BYTES)} bytes")

seen: list[dict] = []


class MockImageHandler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"

    def log_message(self, *args):
        pass

    def do_POST(self):
        length = int(self.headers.get("Content-Length", "0"))
        body = json.loads(self.rfile.read(length).decode("utf-8"))
        seen.append({"path": self.path, "auth": self.headers.get("Authorization"),
                     "model": body.get("model"), "prompt": (body.get("prompt") or "")[:60]})
        payload = json.dumps({"data": [{"b64_json": base64.b64encode(PNG_BYTES).decode()}]}).encode()
        self.send_response(200)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(payload)))
        self.end_headers()
        self.wfile.write(payload)


def call(method: str, path: str, body: dict | None = None):
    data = json.dumps(body).encode("utf-8") if body is not None else None
    request = urllib.request.Request(f"{BACKEND}{path}", data=data, method=method)
    request.add_header("Content-Type", "application/json")
    try:
        with urllib.request.urlopen(request, timeout=120) as response:
            return response.status, response.read()
    except urllib.error.HTTPError as error:
        return error.code, error.read()


def json_call(method: str, path: str, body: dict | None = None):
    status, raw = call(method, path, body)
    return status, (json.loads(raw) if raw else None)


server = ThreadingHTTPServer(("127.0.0.1", MOCK_PORT), MockImageHandler)
threading.Thread(target=server.serve_forever, daemon=True).start()
print(f"mock image service on http://127.0.0.1:{MOCK_PORT}")

try:
    status, settings = json_call("PUT", "/capability-settings/image", {
        "provider": "openai", "endpoint": f"http://127.0.0.1:{MOCK_PORT}/v1",
        "model": "mock-image-v1", "api_key_env": "VMAKER_TEST_IMAGE_KEY", "unit_cost": 0.05,
    })
    assert status == 200 and settings["configured"] is True, (status, settings)
    print("image capability -> openai/mock-image-v1")

    status, project = json_call("POST", "/projects", {
        "name": "剪映草稿实机验证",
        "story": "老放映员把最后一卷胶片交给了一个从没看过电影的孩子。",
        "target_duration_sec": 20, "budget_limit": 10,
    })
    assert status == 201, (status, project)
    project_id = project["id"]

    _, pipeline = json_call("POST", f"/projects/{project_id}/pipeline", {"require_review": False})
    for _ in range(120):
        _, task = json_call("GET", f"/tasks/{pipeline['id']}")
        if task["status"] in ("completed", "failed", "paused", "canceled"):
            break
        time.sleep(1)
    print("pipeline:", task["status"])
    assert task["status"] == "completed", task

    _, assets = json_call("GET", f"/projects/{project_id}/assets")
    by_kind: dict[str, int] = {}
    for asset in assets:
        by_kind[asset["kind"]] = by_kind.get(asset["kind"], 0) + 1
    mimes = sorted({(a["latest_version"] or {}).get("mime_type", "?") for a in assets})
    print("assets by kind:", by_kind, "| mimes:", mimes)
    print(f"mock image requests: {len(seen)}")
    if seen:
        print("  first request:", {k: seen[0][k] for k in ("path", "model")})

    # 一键流水线的 demo_media 阶段刻意只产本地 SVG 占位素材（不花钱），而剪映不支持 SVG。
    # 因此这里再走一次镜头级图像生成（指向 mock 服务），让草稿真的有位图素材可用。
    _, shots = json_call("GET", f"/projects/{project_id}/shots")
    status, image_task = json_call("POST", f"/projects/{project_id}/media-images")
    assert status == 201, (status, image_task)
    for _ in range(120):
        _, task = json_call("GET", f"/tasks/{image_task['id']}")
        if task["status"] in ("completed", "failed", "paused", "canceled"):
            break
        time.sleep(1)
    print("image task:", task["status"], "|", task.get("error") or "")
    assert task["status"] == "completed", task
    assert seen, "the mock image service never received a request"

    _, assets = json_call("GET", f"/projects/{project_id}/assets")
    raster = [a for a in assets if (a["latest_version"] or {}).get("mime_type", "").startswith("image/")
              and "svg" not in (a["latest_version"] or {}).get("mime_type", "")]
    print("raster image assets now:", len(raster))
    assert raster, "no raster image assets were produced by the mock provider"

    print("\n=== 导出剪映草稿 ===")
    status, export = json_call("POST", f"/projects/{project_id}/exports", {"format": "jianying_draft"})
    assert status == 201, (status, export)
    print("format:", export["format"], "| status:", export["status"])
    print("warning:", export.get("warning"))

    artifacts = export["artifacts"]
    print("artifacts:", [(a["kind"], a["mime_type"], a["byte_size"]) for a in artifacts])
    draft_artifacts = [a for a in artifacts if a["kind"] == "jianying_draft"]
    assert draft_artifacts, f"no jianying_draft artifact: {[a['kind'] for a in artifacts]}"

    status, blob = call("GET", f"/exports/{export['id']}")  # metadata endpoint sanity check
    assert status == 200

    # Download the artifact through the real download route.
    download_path = f"/artifacts/{draft_artifacts[0]['id']}/download"
    status, raw = call("GET", download_path)
    assert status == 200, (status, raw[:200])
    print("downloaded draft zip:", len(raw), "bytes")

    archive = zipfile.ZipFile(io.BytesIO(raw))
    names = archive.namelist()
    print("zip entries:", names)
    content_name = next(n for n in names if n.endswith("draft_content.json"))
    meta_name = next(n for n in names if n.endswith("draft_meta_info.json"))
    draft = json.loads(archive.read(content_name).decode("utf-8"))
    meta = json.loads(archive.read(meta_name).decode("utf-8"))

    print("\n--- draft_content.json ---")
    print("canvas:", draft["canvas_config"], "| fps:", draft.get("fps"))
    print("duration(us):", draft["duration"])
    print("material groups:", sorted(k for k, v in draft["materials"].items() if v))

    tracks = draft["tracks"]
    for track in tracks:
        print(f"  track type={track['type']} segments={len(track['segments'])}")

    video_tracks = [t for t in tracks if t["type"] == "video"]
    assert video_tracks and video_tracks[0]["segments"], "draft has no video segments"

    segments = sorted(video_tracks[0]["segments"], key=lambda s: s["target_timerange"]["start"])
    print("\n--- 视频轨排布（微秒） ---")
    cursor = 0
    for index, segment in enumerate(segments):
        start = segment["target_timerange"]["start"]
        duration = segment["target_timerange"]["duration"]
        print(f"  #{index + 1} start={start} duration={duration}")
        assert start == cursor, f"segment {index} starts at {start}, expected contiguous {cursor}"
        cursor += duration
    assert draft["duration"] == cursor, (draft["duration"], cursor)
    print(f"排布连续无空隙，总时长 {cursor} us = {cursor / 1_000_000:.1f}s")

    paths = [m["path"] for m in draft["materials"].get("videos", [])]
    print("\n--- 素材路径 ---")
    missing = [p for p in paths if not Path(p).is_file()]
    for path in paths:
        print(f"  exists={Path(path).is_file()}  {path}")
    assert paths and not missing, f"missing or non-absolute material paths: {missing}"
    print("所有素材路径均为绝对路径且文件存在")

    print("\n--- draft_meta_info.json ---")
    print("draft_name:", repr(meta.get("draft_name")), "| fold_path:", repr(meta.get("draft_fold_path")))
    print("（该字段为空属该库的模板行为，未在真实剪映中验证其影响）")

    warning = export.get("warning") or ""
    if "SVG" in warning or "跳过" in warning:
        print("\nwarning 中如实报告了被跳过的镜头:", warning)

    secret_leak = MOCK_KEY in json.dumps(export, ensure_ascii=False)
    assert not secret_leak
    print("密钥未出现在导出记录中")

    _, diag = json_call("GET", "/system/diagnostics")
    print("\n=== 诊断里的剪映信息 ===")
    for key in ("jianying", "jianying_draft", "jianying_library"):
        if key in diag:
            print(f"  {key}: {json.dumps(diag[key], ensure_ascii=False)}")
    print("  (若上面为空，说明字段名与脚本预期不同，请按实际字段核对)")

    json_call("DELETE", f"/projects/{project_id}")
    print("\nLIVE_JIANYING_OK")
finally:
    try:
        restored = json_call("PUT", "/capability-settings/image", {
            "provider": "demo", "endpoint": "", "model": "demo-svg-v1",
            "api_key_env": "OPENAI_API_KEY", "unit_cost": 0,
        })
        print("image capability restored to:", restored[1]["provider"], restored[1]["model"])
    except Exception as error:  # noqa: BLE001
        print("WARNING: could not restore image capability:", error)
    server.shutdown()
