"""Capability "test connection" assembly.

One place decides what a connection test actually proves. The result deliberately keeps
three separate answers instead of a single green light:

* ``configured`` — the credential the provider needs is present in this process;
* ``reachable``  — the endpoint answers a TCP connection (never an authenticated request);
* ``live``       — a real, billable call was made, and whether it succeeded.

Image generation has no live test on purpose: a single generated frame costs real money and
is not something a "test" button should silently spend. Video has the same rule for a stronger
reason — one clip can cost far more and take minutes, so it is never generated by a test.
"""

from __future__ import annotations

import os
import time

from backend.analysis import AnalysisRepository
from backend.database import Database
from backend.providers import (
    PROBE_TIMEOUT_SECONDS,
    ConnectionCheckError,
    connect_endpoint,
    scrub_secret,
    test_speech_connection,
    test_text_connection,
)
from backend.schemas import CapabilitySettingsUpdate, CapabilityTestRequest

# Every live check is a single minimal request; a longer limit only risks a hung settings page.
LIVE_TIMEOUT_SECONDS = 60
# Capabilities whose real generation is never exercised by a test, with the reason the user sees.
NO_LIVE_TEST_CAPABILITIES = ("image", "video")
NO_LIVE_TEST_NOTICE = {
    "image": "图像能力未做真实生成测试，以免产生一整张图片的费用；以上只验证了配置与网络连通性。",
    "video": ("视频能力不做真实生成测试：真实调用成本高且可能耗时数分钟；"
              "以上只验证了配置与网络连通性。"),
}


def _is_configured(provider: str, api_key_env: str) -> bool:
    """Mirrors ``analysis.capability_configured``; kept local so providers stays import-free."""
    return provider == "demo" or bool(os.getenv(api_key_env))


def _compose_message(*, capability: str, provider: str, live: bool, configured: bool,
                     api_key_env: str, reachable: bool | None, reachability_detail: str,
                     live_detail: str, live_attempted: bool) -> str:
    parts = [f"provider={provider}。"]
    if not configured:
        parts.append(f"未在运行后端的进程中找到环境变量 {api_key_env}，密钥未配置。")
    if reachable is None:
        parts.append("本地占位（demo）能力不联网，因此没有连通性结论。")
    elif reachable:
        parts.append("已通过 TCP 连接验证 endpoint 可达（未发送任何鉴权请求）。")
    elif reachability_detail:
        parts.append(f"连通性检查未通过：{reachability_detail}。")
    else:
        parts.append("连通性检查未通过。")
    if live_attempted:
        parts.append(live_detail or "真实调用已完成。")
    elif live:
        # Say plainly why the requested live call did not happen, so a failure is not mistaken
        # for a silently skipped test.
        if capability in NO_LIVE_TEST_NOTICE:
            parts.append(NO_LIVE_TEST_NOTICE[capability])
        elif not configured:
            parts.append("未执行真实调用：缺少 API key 环境变量。")
        elif reachable is not True:
            parts.append("未执行真实调用：endpoint 不可达。")
        else:  # pragma: no cover - defensive; every other branch is covered above
            parts.append("未执行真实调用。")
    return "".join(parts)


def test_capability_connection(
    database: Database,
    capability: str,
    request: CapabilityTestRequest,
) -> dict[str, object] | None:
    """Test one capability's configuration and return the honest result.

    Returns ``None`` when the capability itself is unknown (the route turns that into a 404).
    A ``CapabilitySettingsUpdate`` validation error propagates so the app can answer 422 with
    exactly the same rules the PUT route uses. Nothing is written to the database: testing a
    configuration is not saving it.
    """
    repo = AnalysisRepository(database)
    saved = repo.get_capability_settings(capability)
    if saved is None:
        return None

    # Only fields the caller actually sent override the saved row; omitted (or explicitly null)
    # fields fall back to what is stored, so a test can validate a draft configuration.
    supplied = {name: value for name, value in request.model_dump().items() if value is not None}
    supplied.pop("live", None)
    merged = {**saved, **supplied}
    config = CapabilitySettingsUpdate.model_validate(merged)

    provider = config.provider
    endpoint = config.endpoint
    model = config.model
    api_key_env = config.api_key_env
    is_demo = provider == "demo"
    # Video is asynchronous and no cheaper than image, so it is in the same "never generate" set.
    no_live_test = capability in NO_LIVE_TEST_CAPABILITIES
    configured = _is_configured(provider, api_key_env)
    # A capability that never runs a live call must not look like one either.
    live_requested = bool(request.live) and not no_live_test
    # What the *caller* asked for, which is what the message must explain: for these capabilities
    # this stays true even though no live call will be made, so the reason is stated, not implied.
    live_asked = bool(request.live)

    started = time.monotonic()
    reachable: bool | None = None
    reachability_detail = ""
    if not is_demo:
        if not endpoint:
            # Reported separately from "unreachable": nothing was even attempted.
            reachable, reachability_detail = False, "缺少 endpoint"
        else:
            reachable, reachability_detail = connect_endpoint(endpoint, PROBE_TIMEOUT_SECONDS)

    live_attempted = False
    live_ok = False
    live_detail = ""
    if live_requested and configured and reachable is True:
        live_attempted = True
        api_key = os.getenv(api_key_env) or ""
        live_call = test_text_connection if capability == "text" else test_speech_connection
        try:
            live_detail = live_call(endpoint=endpoint, model=model, api_key=api_key,
                                    timeout=LIVE_TIMEOUT_SECONDS)
            live_ok = True
        except ConnectionCheckError as exc:
            # The message is already specific and scrubbed of anything secret-looking.
            live_detail = str(exc)
            live_ok = False

    if live_attempted:
        ok = configured and live_ok
    elif is_demo:
        ok = configured
    else:
        ok = configured and reachable is True

    message = scrub_secret(
        _compose_message(
            capability=capability, provider=provider, live=live_asked, configured=configured,
            api_key_env=api_key_env, reachable=reachable, reachability_detail=reachability_detail,
            live_detail=live_detail, live_attempted=live_attempted,
        ),
        os.getenv(api_key_env) or "",
    )
    latency_ms = max(0, int(round((time.monotonic() - started) * 1000)))
    return {
        "capability": capability,
        "provider": provider,
        "model": model,
        "live": live_attempted,
        "configured": configured,
        "reachable": reachable,
        "ok": bool(ok),
        "message": message,
        "latency_ms": latency_ms,
    }
